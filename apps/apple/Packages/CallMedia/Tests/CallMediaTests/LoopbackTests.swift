import XCTest
import AppCore
import CallCore
@testable import CallMedia

/// Test-only audio source: writes a 440 Hz sine into the capture path through the capture hook,
/// so the encoder has real audio to send and DTX does not silence it. The hook runs only when the
/// audio pipeline captures; a runner with no input device never calls it (see `testSendProfileReachesEncoder`).
final class ToneProcessor: CaptureProcessor, @unchecked Sendable {
    private let lock = NSLock()
    private var phase = 0.0, rate = 48_000.0, _frames = 0
    var frames: Int { lock.withLock { _frames } }
    func initialize(sampleRateHz: Int, channels: Int) { lock.withLock { rate = Double(sampleRateHz) } }
    func process(channels: UnsafePointer<UnsafeMutablePointer<Float>>, frames: Int, channelCount: Int) {
        lock.lock(); defer { lock.unlock() }
        let step = 2 * Double.pi * 440 / rate
        for i in 0..<frames {
            let v = Float(0.3 * sin(phase)); phase += step
            for c in 0..<channelCount { channels[c][i] = v }
        }
        _frames += 1
    }
    func reset() {}
}

/// Holds each side's candidates until the other side has its remote description (add throws before that).
final class CandidateRelay: @unchecked Sendable {
    private let lock = NSLock()
    private var ready: Set<String> = [], pending: [String: [IceCandidate]] = [:]
    private var sessions: [String: WebRTCMediaSession] = [:]
    func register(_ name: String, _ s: WebRTCMediaSession) { lock.withLock { sessions[name] = s } }
    /// A candidate generated by the peer of `target`.
    func deliver(to target: String, _ c: IceCandidate) async {
        let s: WebRTCMediaSession? = lock.withLock {
            if ready.contains(target) { return sessions[target] }
            pending[target, default: []].append(c); return nil
        }
        if let s { try? await s.add(c) }
    }
    func remoteDescriptionSet(on target: String) async {
        let (s, queued): (WebRTCMediaSession?, [IceCandidate]) = lock.withLock {
            ready.insert(target); return (sessions[target], pending.removeValue(forKey: target) ?? [])
        }
        for c in queued { try? await s?.add(c) }
    }
}

final class LoopbackTests: XCTestCase {
    static let tone = ToneProcessor()
    private let relay = CandidateRelay()
    override class func setUp() { MediaFactory.captureProcessor = tone }  // before the first shared()

    private var pumps: [Task<Void, Never>] = []
    private var iceStates: [String: [IceState]] = [:]
    private var localCandidates: [String: Int] = [:]
    private let lock = NSLock()

    override func tearDown() { pumps.forEach { $0.cancel() }; pumps = [] }

    private func record(_ name: String, _ e: MediaEvent) {
        lock.withLock {
            switch e {
            case .iceState(let s): iceStates[name, default: []].append(s)
            case .localCandidate: localCandidates[name, default: 0] += 1
            default: break
            }
        }
    }
    private func has(_ name: String, _ s: IceState) -> Bool { lock.withLock { iceStates[name]?.contains(s) ?? false } }

    /// Forwards candidates to `to` (when given) and records every event.
    private func pump(_ name: String, _ from: WebRTCMediaSession, peer: String?) {
        pumps.append(Task { [self] in
            for await e in from.events {
                record(name, e)
                if case .localCandidate(let c) = e, let peer { await relay.deliver(to: peer, c) }
            }
        })
    }

    private func wait(_ timeout: TimeInterval, _ cond: () -> Bool) async -> Bool {
        let end = Date().addingTimeInterval(timeout)
        while Date() < end { if cond() { return true }; try? await Task.sleep(nanoseconds: 100_000_000) }
        return cond()
    }

    /// `send` is what A may send (applied to B's answer); B asks to receive `peerReceive`.
    private func connected(send: DataMode = .balanced, peerReceive: DataMode? = nil) async throws -> (WebRTCMediaSession, WebRTCMediaSession) {
        let a = WebRTCMediaSession(), b = WebRTCMediaSession()
        try await a.configure(iceServers: [], policy: .all, video: false)
        try await b.configure(iceServers: [], policy: .all, video: false)
        relay.register("A", a); relay.register("B", b)
        pump("A", a, peer: "B"); pump("B", b, peer: "A")
        let p = AudioProfile.for(send), pb = AudioProfile.for(peerReceive ?? send)
        let offer = try await a.makeOffer(receive: p, iceRestart: false)
        let answer = try await b.acceptOffer(offer, send: p, receive: pb)
        await relay.remoteDescriptionSet(on: "B")
        try await a.acceptAnswer(answer, send: p)
        await relay.remoteDescriptionSet(on: "A")
        return (a, b)
    }

    func testLoopbackConnects() async throws {
        let (a, b) = try await connected()
        let ok = await wait(10) { self.has("A", .connected) && self.has("B", .connected) }
        XCTAssertTrue(ok)
        await a.close(); await b.close()
    }

    func testLocalOfferIsMunged() async throws {
        let a = WebRTCMediaSession()
        try await a.configure(iceServers: [], policy: .all, video: false)
        let offer = try await a.makeOffer(receive: .for(.ultraLow), iceRestart: false)
        XCTAssertTrue(offer.contains("a=ptime:60"))
        XCTAssertTrue(offer.contains("maxaveragebitrate=10000"))
        XCTAssertTrue(offer.contains("a=fingerprint:sha-256"))
        XCTAssertTrue(offer.contains("UDP/TLS/RTP/SAVPF"))
        await a.close()
    }

    /// With the tone playing, an encoder that ignored the profile would send 30 kbps or more
    /// (Opus default). B asks to receive `.high`, so its answer does not carry the 10 kbps cap itself:
    /// the cap on A can only come from the munge A applies to the remote answer (`send: .ultraLow`),
    /// and this fails if that munge is removed.
    func testSendProfileReachesEncoder() async throws {
        let (a, b) = try await connected(send: .ultraLow, peerReceive: .high)
        let up = await wait(10) { self.has("A", .connected) }
        XCTAssertTrue(up, "the call must connect")
        let s0 = await a.stats()
        let f0 = Self.tone.frames
        try await Task.sleep(nanoseconds: 5_000_000_000)
        let s1 = await a.stats()
        // The hook runs only if the runner captures audio. Without an input device there is no source,
        // and the assertions below would not mean anything (the skip comes after closing the sessions).
        let toneRan = Self.tone.frames != f0
        let bps = Double(s1.bytesSent - s0.bytesSent) * 8 / 5
        await a.close(); await b.close()   // close before a possible skip
        try XCTSkipIf(!toneRan, "no audio capture on this runner, so the tone never played")
        XCTAssertGreaterThan(bps, 2_000, "the tone must be sent")
        XCTAssertLessThanOrEqual(bps, 14_000)
    }

    func testRelayOnlyGathersOnlyRelayCandidates() async throws {
        let a = WebRTCMediaSession()
        try await a.configure(iceServers: [], policy: .relay, video: false)
        pump("A", a, peer: nil)
        _ = try await a.makeOffer(receive: .for(.balanced), iceRestart: false)
        try await Task.sleep(nanoseconds: 3_000_000_000)
        XCTAssertEqual(lock.withLock { localCandidates["A"] ?? 0 }, 0)
        await a.close()
        // Positive control: the same flow with policy .all does gather, so silence above means the filter works.
        let c = WebRTCMediaSession()
        try await c.configure(iceServers: [], policy: .all, video: false)
        pump("C", c, peer: nil)
        _ = try await c.makeOffer(receive: .for(.balanced), iceRestart: false)
        let gathered = await wait(3) { self.lock.withLock { self.localCandidates["C"] ?? 0 } > 0 }
        XCTAssertTrue(gathered)
        await c.close()
    }

    func testIceRestartChangesUfrag() async throws {
        let (a, b) = try await connected()
        _ = await wait(10) { self.has("A", .connected) }
        let p = AudioProfile.for(.balanced)
        let first = try await a.makeOffer(receive: p, iceRestart: false)
        try await a.rollback()
        let restart = try await a.makeOffer(receive: p, iceRestart: true)
        XCTAssertNotEqual(Self.ufrag(first), Self.ufrag(restart))
        XCTAssertNotNil(Self.ufrag(restart))
        await a.close(); await b.close()
    }

    /// After a real rollback the session is stable, so the callee's answer to the abandoned offer is refused.
    /// Without the rollback `have-local-offer` would accept it.
    func testRollback() async throws {
        let a = WebRTCMediaSession(), b = WebRTCMediaSession()
        try await a.configure(iceServers: [], policy: .all, video: false)
        try await b.configure(iceServers: [], policy: .all, video: false)
        let p = AudioProfile.for(.balanced)
        let offer = try await a.makeOffer(receive: p, iceRestart: false)
        let answer = try await b.acceptOffer(offer, send: p, receive: p)
        try await a.rollback()
        do {
            try await a.acceptAnswer(answer, send: p)
            XCTFail("the answer must be refused after the rollback")
        } catch {}
        // And A can start over.
        let again = try await a.makeOffer(receive: p, iceRestart: false)
        XCTAssertTrue(again.contains("a=ice-ufrag"))
        await a.close(); await b.close()
    }

    private static func ufrag(_ sdp: String) -> String? {
        sdp.components(separatedBy: "\r\n").first { $0.hasPrefix("a=ice-ufrag:") }
    }
}
