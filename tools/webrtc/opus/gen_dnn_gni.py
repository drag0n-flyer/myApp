#!/usr/bin/env python3
"""Writes third_party/opus/dnn_sources.gni from opus's lpcnet_sources.mk.

Usage: gen_dnn_gni.py <lpcnet_sources.mk> <out.gni> [--version <opus version>]

The version defaults to PACKAGE_VERSION in the package_version file that sits
next to the .mk file in the release tarball. DRED sources are never listed:
the project defers DRED (GOAL.md section 4).
"""

import argparse
import os
import re
import sys

# (gn list name, variable in lpcnet_sources.mk), in output order.
LISTS = (
    ("deep_plc_sources", "DEEP_PLC_SOURCES"),
    ("osce_sources", "OSCE_SOURCES"),
    ("dnn_neon_sources", "DNN_SOURCES_NEON"),
    ("dnn_dotprod_sources", "DNN_SOURCES_DOTPROD"),
)

HEADER = "# Generated by tools/webrtc/opus/gen_dnn_gni.py from opus {version}. Do not edit."


def parse_mk(text):
    """Returns {variable: [file, ...]}. Handles backslash continuations and
    single-line assignments. Files keep their order from the .mk file."""
    text = text.replace("\\\r\n", "\\\n")
    variables = {}
    lines = iter(text.split("\n"))
    for line in lines:
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$", line)
        if not match:
            continue
        name, rest = match.group(1), match.group(2)
        files = []
        while True:
            continued = rest.rstrip().endswith("\\")
            files += rest.rstrip().rstrip("\\").split()
            if not continued:
                break
            rest = next(lines, "")
        variables[name] = files
    return variables


def generate(mk_text, version):
    variables = parse_mk(mk_text)
    out = [HEADER.format(version=version), ""]
    for gn_name, mk_name in LISTS:
        if mk_name not in variables:
            raise ValueError("%s is not defined in the .mk file" % mk_name)
        out.append("%s = [" % gn_name)
        out += ['  "src/%s",' % path for path in variables[mk_name]]
        out.append("]")
        out.append("")
    return "\n".join(out[:-1]) + "\n"


def version_from_package_version(mk_path):
    path = os.path.join(os.path.dirname(os.path.abspath(mk_path)), "package_version")
    try:
        with open(path) as f:
            match = re.search(r'^PACKAGE_VERSION="([^"]+)"', f.read(), re.M)
    except OSError as err:
        raise ValueError("no --version given and cannot read %s: %s" % (path, err))
    if not match:
        raise ValueError("no PACKAGE_VERSION in %s" % path)
    return match.group(1)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("mk", help="lpcnet_sources.mk from the opus tarball")
    parser.add_argument("out", help="gni file to write")
    parser.add_argument("--version", help="opus version for the header line")
    args = parser.parse_args(argv)
    try:
        with open(args.mk) as f:
            mk_text = f.read()
        version = args.version or version_from_package_version(args.mk)
        text = generate(mk_text, version)
    except (OSError, ValueError) as err:
        print("error: %s" % err, file=sys.stderr)
        return 1
    with open(args.out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
