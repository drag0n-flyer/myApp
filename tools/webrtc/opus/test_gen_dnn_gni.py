"""Tests for gen_dnn_gni.py. Run from the repo root:

    python3 -m unittest tools/webrtc/opus/test_gen_dnn_gni.py

test_real_tarball needs the unpacked opus 1.6 tarball that
tools/webrtc/opus-probe/run-tests.sh leaves in ${TMPDIR:-/tmp}/opus-probe.
"""

import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "gen_dnn_gni.py")
sys.path.insert(0, HERE)

FIXTURE_MK = """\
DEEP_PLC_SOURCES = \\
dnn/burg.c \\
dnn/nnet.c

OSCE_SOURCES = \\
dnn/osce.c

DNN_SOURCES_DOTPROD = dnn/arm/nnet_dotprod.c
DNN_SOURCES_NEON = dnn/arm/nnet_neon.c
"""

HEADER_1_6 = "# Generated by tools/webrtc/opus/gen_dnn_gni.py from opus 1.6. Do not edit."


def run_gen(mk_text, version="1.6"):
    """Runs the script on mk_text. Returns (exit code, stderr, gni text or None)."""
    with tempfile.TemporaryDirectory() as tmp:
        mk = os.path.join(tmp, "lpcnet_sources.mk")
        out = os.path.join(tmp, "out.gni")
        with open(mk, "w") as f:
            f.write(mk_text)
        proc = subprocess.run(
            [sys.executable, "-I", GEN, mk, out, "--version", version],
            capture_output=True,
            text=True,
        )
        text = None
        if os.path.exists(out):
            with open(out) as f:
                text = f.read()
        return proc.returncode, proc.stderr, text


class GenDnnGniTest(unittest.TestCase):
    def test_lists(self):
        code, err, text = run_gen(FIXTURE_MK)
        self.assertEqual(code, 0, err)
        self.assertIn('deep_plc_sources = [\n  "src/dnn/burg.c",\n  "src/dnn/nnet.c",\n]', text)
        self.assertIn('osce_sources = [\n  "src/dnn/osce.c",\n]', text)

    def test_order_and_single_line_lists(self):
        code, err, text = run_gen(FIXTURE_MK)
        self.assertEqual(code, 0, err)
        names = [
            line.split(" = ")[0]
            for line in text.splitlines()
            if line.endswith(" = [")
        ]
        self.assertEqual(
            names,
            ["deep_plc_sources", "osce_sources", "dnn_neon_sources", "dnn_dotprod_sources"],
        )
        self.assertIn('dnn_neon_sources = [\n  "src/dnn/arm/nnet_neon.c",\n]', text)
        self.assertIn('dnn_dotprod_sources = [\n  "src/dnn/arm/nnet_dotprod.c",\n]', text)

    def test_header(self):
        code, err, text = run_gen(FIXTURE_MK)
        self.assertEqual(code, 0, err)
        self.assertEqual(text.splitlines()[0], HEADER_1_6)

    def test_missing_variable_fails(self):
        code, err, text = run_gen("DEEP_PLC_SOURCES = \\\ndnn/burg.c\n")
        self.assertNotEqual(code, 0)
        self.assertIn("OSCE_SOURCES", err)
        self.assertIsNone(text)

    def test_real_tarball(self):
        mk = os.path.join(
            os.environ.get("TMPDIR", "/tmp"),
            "opus-probe",
            "opus-1.6",
            "lpcnet_sources.mk",
        )
        if not os.path.exists(mk):
            self.skipTest("run tools/webrtc/opus-probe/run-tests.sh first to unpack opus 1.6")
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, "dnn_sources.gni")
            proc = subprocess.run(
                [sys.executable, "-I", GEN, mk, out, "--version", "1.6"],
                capture_output=True,
                text=True,
            )
            self.assertEqual(proc.returncode, 0, proc.stderr)
            with open(out) as f:
                text = f.read()
        for want in (
            '"src/dnn/nolace_data.c"',
            '"src/dnn/bbwenet_data.c"',
            '"src/dnn/plc_data.c"',
            '"src/dnn/arm/nnet_dotprod.c"',
        ):
            self.assertIn(want, text)
        self.assertNotIn("dred", text.lower())
        self.assertEqual(text.splitlines()[0], HEADER_1_6)


if __name__ == "__main__":
    unittest.main()
